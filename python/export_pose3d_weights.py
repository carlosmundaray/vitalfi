"""
VitalFi — Export Pose3D Model Weights to Kotlin FloatArrays

Reads a trained PyTorch WiFiPoseEstimator model (.pt) and generates
Kotlin constant arrays that can be pasted into Pose3DOnDeviceEngine.kt.

Usage:
    python export_pose3d_weights.py --model pose3d_trained.pt --output pose3d_weights.kt

If no model file is provided, generates random initialization weights
for testing the pipeline end-to-end.
"""

from __future__ import annotations

import argparse
from pathlib import Path
import numpy as np

try:
    import torch
    from pose3d_model import WiFiPoseEstimator, create_model
    HAS_TORCH = True
except ImportError:
    HAS_TORCH = False


def float_array_to_kotlin(name: str, arr: np.ndarray, indent: int = 4) -> str:
    """Convert a numpy array to a Kotlin FloatArray literal."""
    flat = arr.flatten().astype(np.float32)
    prefix = " " * indent
    
    # Format values in rows of 8
    vals = []
    for i, v in enumerate(flat):
        vals.append(f"{v:.6f}f")
    
    # Split into lines of 8 values each
    lines = []
    for i in range(0, len(vals), 8):
        chunk = ", ".join(vals[i:i+8])
        lines.append(f"{prefix}    {chunk},")
    
    body = "\n".join(lines)
    return f"{prefix}private val {name} = floatArrayOf(\n{body}\n{prefix})"


def export_from_model(model: 'WiFiPoseEstimator', output_path: Path) -> None:
    """Export all weights from a trained model."""
    sd = model.state_dict()
    
    lines = [
        "// ═══════════════════════════════════════════════════════════",
        "// AUTO-GENERATED by export_pose3d_weights.py",
        "// DO NOT EDIT MANUALLY",
        "// ═══════════════════════════════════════════════════════════",
        "",
    ]
    
    # Map PyTorch state_dict keys to Kotlin variable names
    weight_map = {
        # Conv Block 1
        "spatial_encoder.conv_blocks.0.weight": "conv1W",
        "spatial_encoder.conv_blocks.0.bias": "conv1B",
        "spatial_encoder.conv_blocks.1.weight": "bn1G",
        "spatial_encoder.conv_blocks.1.bias": "bn1B",
        "spatial_encoder.conv_blocks.1.running_mean": "bn1M",
        "spatial_encoder.conv_blocks.1.running_var": "bn1V",
        # Conv Block 2
        "spatial_encoder.conv_blocks.4.weight": "conv2W",
        "spatial_encoder.conv_blocks.4.bias": "conv2B",
        "spatial_encoder.conv_blocks.5.weight": "bn2G",
        "spatial_encoder.conv_blocks.5.bias": "bn2B",
        "spatial_encoder.conv_blocks.5.running_mean": "bn2M",
        "spatial_encoder.conv_blocks.5.running_var": "bn2V",
        # Conv Block 3
        "spatial_encoder.conv_blocks.8.weight": "conv3W",
        "spatial_encoder.conv_blocks.8.bias": "conv3B",
        "spatial_encoder.conv_blocks.9.weight": "bn3G",
        "spatial_encoder.conv_blocks.9.bias": "bn3B",
        "spatial_encoder.conv_blocks.9.running_mean": "bn3M",
        "spatial_encoder.conv_blocks.9.running_var": "bn3V",
        # Keypoint head
        "keypoint_head.0.weight": "kpW1",
        "keypoint_head.0.bias": "kpB1",
        "keypoint_head.2.weight": "kpW2",  # skip dropout at index 1
        "keypoint_head.2.bias": "kpB2",
        # Posture head
        "posture_head.0.weight": "posW1",
        "posture_head.0.bias": "posB1",
        "posture_head.2.weight": "posW2",
        "posture_head.2.bias": "posB2",
        # Confidence head
        "confidence_head.0.weight": "confW1",
        "confidence_head.0.bias": "confB1",
        "confidence_head.2.weight": "confW2",
        "confidence_head.2.bias": "confB2",
    }
    
    for pt_key, kt_name in weight_map.items():
        if pt_key in sd:
            arr = sd[pt_key].cpu().numpy()
            lines.append(f"// {pt_key} shape={arr.shape} ({arr.size} params)")
            lines.append(float_array_to_kotlin(kt_name, arr))
            lines.append("")
    
    output_path.write_text("\n".join(lines), encoding="utf-8")
    
    total = sum(sd[k].numel() for k in weight_map if k in sd)
    size_kb = total * 4 / 1024
    print(f"[Export] Wrote {len(weight_map)} weight arrays ({total:,} params, ~{size_kb:.1f} KB)")
    print(f"[Export] Output: {output_path}")


def export_random_weights(output_path: Path) -> None:
    """Generate random initialization weights for pipeline testing."""
    rng = np.random.default_rng(42)
    
    lines = [
        "// ═══════════════════════════════════════════════════════════",
        "// AUTO-GENERATED RANDOM WEIGHTS (for pipeline testing)",
        "// Replace with trained weights using:",
        "//   python export_pose3d_weights.py --model trained.pt",
        "// ═══════════════════════════════════════════════════════════",
        "",
    ]
    
    # Define shapes matching Pose3DOnDeviceEngine (HIDDEN_DIM=32)
    H = 32  # hidden dim
    weight_specs = [
        ("conv1W", (16, 2, 3, 1)),
        ("conv1B", (16,)),
        ("bn1G", (16,)), ("bn1B", (16,)), ("bn1M", (16,)), ("bn1V", (16,)),
        ("conv2W", (32, 16, 3, 1)),
        ("conv2B", (32,)),
        ("bn2G", (32,)), ("bn2B", (32,)), ("bn2M", (32,)), ("bn2V", (32,)),
        ("conv3W", (H, 32, 3, 1)),
        ("conv3B", (H,)),
        ("bn3G", (H,)), ("bn3B", (H,)), ("bn3M", (H,)), ("bn3V", (H,)),
        ("tconv1W", (H, H, 5)),
        ("tconv1B", (H,)),
        ("tconv2W", (H, H, 3)),
        ("tconv2B", (H,)),
        ("attnW", (H,)),
        ("attnB", (1,)),
        ("kpW1", (H * 2, H)),
        ("kpB1", (H * 2,)),
        ("kpW2", (17 * 3, H * 2)),
        ("kpB2", (17 * 3,)),
        ("posW1", (H, H)),
        ("posB1", (H,)),
        ("posW2", (4, H)),
        ("posB2", (4,)),
        ("confW1", (H, H)),
        ("confB1", (H,)),
        ("confW2", (17, H)),
        ("confB2", (17,)),
    ]
    
    total = 0
    for name, shape in weight_specs:
        size = int(np.prod(shape))
        total += size
        
        # Use appropriate initialization
        if "W" in name and "bn" not in name.lower():
            fan_in = int(np.prod(shape[1:]))
            std = np.sqrt(2.0 / max(fan_in, 1))
            arr = rng.normal(0, std, size=shape).astype(np.float32)
        elif name.endswith("V"):  # running_var
            arr = np.ones(shape, dtype=np.float32)
        elif name.endswith("G"):  # gamma
            arr = np.ones(shape, dtype=np.float32)
        else:
            arr = np.zeros(shape, dtype=np.float32)
        
        lines.append(f"// {name} shape={shape} ({size} params)")
        lines.append(float_array_to_kotlin(name, arr))
        lines.append("")
    
    output_path.write_text("\n".join(lines), encoding="utf-8")
    size_kb = total * 4 / 1024
    print(f"[Export] Generated random weights: {total:,} params (~{size_kb:.1f} KB)")
    print(f"[Export] Output: {output_path}")


def main():
    parser = argparse.ArgumentParser(description="Export Pose3D weights to Kotlin")
    parser.add_argument("--model", type=str, default=None,
                        help="Path to trained .pt model file")
    parser.add_argument("--output", type=str, default="pose3d_weights.kt",
                        help="Output Kotlin file")
    args = parser.parse_args()
    
    output_path = Path(args.output)
    
    if args.model and HAS_TORCH:
        print(f"[Export] Loading model from {args.model}")
        model = create_model(num_subcarriers=64, max_nodes=1, pretrained_path=args.model)
        export_from_model(model, output_path)
    else:
        if args.model and not HAS_TORCH:
            print("[Export] PyTorch not available. Generating random weights for testing.")
        else:
            print("[Export] No model file provided. Generating random weights for testing.")
        export_random_weights(output_path)


if __name__ == "__main__":
    main()
