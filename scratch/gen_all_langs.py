# Write a generator loop that applies language maps, and writes XML files
def generate_xml_for_lang(lang_code, overrides):
    lines = ['<?xml version="1.0" encoding="utf-8"?>\n<resources>']
    for k in all_keys:
        val = overrides.get(k, en_dict.get(k, ""))
        # escape for XML
        clean_val = val.replace('&', '&amp;') if '&amp;' not in val else val
        clean_val = clean_val.replace('<', '&lt;').replace('>', '&gt;')
        # replace double-escaped &amp;lt;
        clean_val = clean_val.replace('&amp;lt;', '&lt;').replace('&amp;gt;', '&gt;').replace('&amp;amp;', '&amp;')
        lines.append(f'    <string name="{k}">{clean_val}</string>')
    lines.append('</resources>\n')
    return '\n'.join(lines)

