for src_alias, target in aliases:
    alias_dir = os.path.join(res_dir, f"values-{src_alias}")
    os.makedirs(alias_dir, exist_ok=True)
    target_file = os.path.join(res_dir, f"values-{target}", "strings.xml")
    if os.path.exists(target_file):
        with open(target_file, "r", encoding="utf-8") as f:
            content = f.read()
        with open(os.path.join(alias_dir, "strings.xml"), "w", encoding="utf-8") as f:
            f.write(content)
        print(f"Copied alias {src_alias} -> {target}")

