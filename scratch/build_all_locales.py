# Write each language file
for code in lang_codes:
    lang_dir = os.path.join(res_dir, f"values-{code}")
    os.makedirs(lang_dir, exist_ok=True)
    existing = existing_dicts.get(code, {})
    
    xml_lines = ['<?xml version="1.0" encoding="utf-8"?>\n<resources>']
    for k in all_keys:
        val = None
        # Check new key translations first
        if k in new_keys_translations and code in new_keys_translations[k]:
            val = new_keys_translations[k][code]
        elif k in existing:
            val = existing[k]
        else:
            val = en_dict.get(k, "")
        
        # XML escaping
        clean = val.replace('&', '&amp;') if '&amp;' not in val else val
        clean = clean.replace('<', '&lt;').replace('>', '&gt;')
        clean = clean.replace('&amp;lt;', '&lt;').replace('&amp;gt;', '&gt;').replace('&amp;amp;', '&amp;')
        clean = clean.replace("'", "\\'") if "'" in clean and "\\'" not in clean else clean
        xml_lines.append(f'    <string name="{k}">{clean}</string>')
    xml_lines.append('</resources>\n')
    
    with open(os.path.join(lang_dir, "strings.xml"), "w", encoding="utf-8") as f:
        f.write('\n'.join(xml_lines))
    print(f"Generated {code}: {len(all_keys)} keys")

