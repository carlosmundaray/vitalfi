def escape_xml_android(text):
    # Handle XML special characters
    # First unescape existing entities to avoid double escaping
    text = text.replace("&amp;", "&").replace("&lt;", "<").replace("&gt;", ">")
    # Escape & to &amp;
    text = text.replace("&", "&amp;")
    # Escape < and >
    text = text.replace("<", "&lt;").replace(">", "&gt;")
    # Escape single quotes for Android XML strings
    text = re.sub(r"(?<!\\)'", r"\'", text)
    return text

def parse_strings_xml(filepath):
    if not os.path.exists(filepath):
        return {}
    with open(filepath, "r", encoding="utf-8") as f:
        content = f.read()
    # parse with regex to be robust against unescaped XML
    items = re.findall(r'<string name="([^"]+)">([\s\S]*?)</string>', content)
    return {k: v for k, v in items}

